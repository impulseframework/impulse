// servedCollection is a permission collection in the form the generator writes one:
// a method, a global list with fields, a tenant's list, and a resource whose permission
// has no constant.
const servedCollection = `// Code generated by resourcegeneration. DO NOT EDIT.
// Source: pkg/resources

package router

import (
	"github.com/impulseframework/impulse/accesstypes"
	"github.com/impulseframework/impulse/resource"
)

func Collection() *resource.GeneratedCollection {
	return resource.MustNewGeneratedCollection(resource.CollectionData{
		Resources: []resource.CollectionResource{
			{
				Name:        "AssignStaffRole",
				Scope:       accesstypes.GlobalPermissionScope,
				Permissions: []accesstypes.Permission{accesstypes.Execute},
				Attributes: []resource.AttributeData{
					{Name: "role", Column: "Role", Type: "string"},
				},
			},
			{
				Name:        "Berths",
				Scope:       accesstypes.GlobalPermissionScope,
				Permissions: []accesstypes.Permission{accesstypes.Create, accesstypes.Delete, accesstypes.List, accesstypes.Read, accesstypes.Update},
				Tags: []resource.TagData{
					{Name: "id"},
					{Name: "name", Permissions: []accesstypes.Permission{accesstypes.Create, accesstypes.List, accesstypes.Read, accesstypes.Update}},
					{Name: "depth", Permissions: []accesstypes.Permission{accesstypes.List, accesstypes.Read}, Masking: resource.MaskingPositional},
				},
				Order: []accesstypes.Tag{"name"},
			},
			{
				Name:        "Moorings",
				Scope:       accesstypes.DomainPermissionScope,
				Permissions: []accesstypes.Permission{accesstypes.List},
				Tags: []resource.TagData{
					{Name: "berthId", Permissions: []accesstypes.Permission{accesstypes.List}},
				},
			},
			{
				Name:        "Surveys",
				Scope:       accesstypes.PermissionScope("harbor"),
				Permissions: []accesstypes.Permission{accesstypes.Permission("Approve")},
			},
		},
	})
}
`

func TestParseCollection(t *testing.T) {
	t.Parallel()

	got, err := ParseCollection("pkg/router/zz_gen_collection.go", []byte(servedCollection))
	if err != nil {
		t.Fatalf("ParseCollection() error = %v", err)
	}
	want := []*ServedResource{
		{Name: "AssignStaffRole", Scope: ScopeGlobal, Permissions: []string{"Execute"}},
		{
			Name: "Berths", Scope: ScopeGlobal, Permissions: []string{"Create", "Delete", "List", "Read", "Update"},
			Fields: map[string][]string{"id": nil, "name": {"Create", "List", "Read", "Update"}, "depth": {"List", "Read"}},
		},
		{Name: "Moorings", Scope: ScopeDomain, Permissions: []string{"List"}, Fields: map[string][]string{"berthId": {"List"}}},
		{Name: "Surveys", Scope: "harbor", Permissions: []string{"Approve"}},
	}
	if diff := cmp.Diff(want, got, cmpopts.EquateEmpty()); diff != "" {
		t.Errorf("ParseCollection() mismatch (-want +got):\n%s", diff)
	}
}

func TestParseCollection_refuses(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		src  string
		want string
	}{
		{name: "a file that is not Go", src: "package router\nfunc {", want: "parser.ParseFile()"},
		{name: "a file with no collection", src: "package router\n", want: "holds no resource.CollectionData literal"},
		{
			name: "a resource with no name",
			src:  strings.Replace(servedCollection, `Name:        "Berths",`, "", 1),
			want: "a resource of the collection has no name this can read",
		},
		{
			name: "a scope that is a variable",
			src:  strings.Replace(servedCollection, "accesstypes.DomainPermissionScope", "scope", 1),
			want: "the resource Moorings has no scope this can read",
		},
		{
			name: "a permission that is a variable",
			src:  strings.Replace(servedCollection, "[]accesstypes.Permission{accesstypes.List},\n\t\t\t\tTags", "[]accesstypes.Permission{list},\n\t\t\t\tTags", 1),
			want: "the resource Moorings has permissions this cannot read",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			_, err := ParseCollection("pkg/router/zz_gen_collection.go", []byte(tt.src))
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Errorf("ParseCollection() error = %v, want one saying %q", err, tt.want)
			}
		})
	}
}

func TestApp_Served(t *testing.T) {
	t.Parallel()

	const program = `package main

import "github.com/impulseframework/impulse/generation"

func main() {
	generation.NewResourceGenerator(nil, "pkg/resources", "schema/migrations", nil,
		generation.GenerateRoutes("%s", "api"),
	)
}
`
	write := func(t *testing.T, root, rel, content string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(filepath.Join(root, rel)), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(root, rel), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	discover := func(t *testing.T, files map[string]string) *App {
		t.Helper()
		root := t.TempDir()
		write(t, root, "go.mod", "module example.com/harbor\n\ngo 1.26.6\n")
		for rel, content := range files {
			write(t, root, rel, content)
		}
		a, err := Discover(root)
		if err != nil {
			t.Fatalf("Discover() error = %v", err)
		}

		return a
	}

	t.Run("an application that has generated nothing serves nothing this can read", func(t *testing.T) {
		t.Parallel()

		a := discover(t, map[string]string{"cmd/generate/resourcegenerator/main.go": strings.Replace(program, "%s", "pkg/router", 1)})
		if len(a.Generators) != 1 || a.Generators[0].RoutesDir() != "pkg/router" {
			t.Fatalf("the fixture's generator is not read with its routes directory: %+v", a.Generators)
		}
		served, err := a.Served()
		if err != nil || served != nil {
			t.Errorf("Served() = %v, %v, want nil, nil", served, err)
		}
	})

	t.Run("the collections of two generators are one application's", func(t *testing.T) {
		t.Parallel()

		// Each collection says something of a resource the other does not, so that what the
		// application serves is neither one's alone, whichever is read first.
		other := strings.NewReplacer(
			`"Moorings"`, `"Tides"`,
			"accesstypes.Execute}", "accesstypes.Execute, accesstypes.Read}",
			`accesstypes.Permission("Approve")`, `accesstypes.Permission("Sign")`,
			`{Name: "id"}`, `{Name: "id", Permissions: []accesstypes.Permission{accesstypes.Read}}`,
			"{accesstypes.Create, accesstypes.List, accesstypes.Read, accesstypes.Update}},", "{accesstypes.Delete}},",
		).Replace(servedCollection)
		a := discover(t, map[string]string{
			"cmd/generate/resourcegenerator/main.go": strings.Replace(program, "%s", "pkg/router", 1),
			"cmd/generate/portalgenerator/main.go":   strings.Replace(program, "%s", "pkg/portalrouter", 1),
			"pkg/router/" + CollectionFileName:       servedCollection,
			"pkg/portalrouter/" + CollectionFileName: other,
		})
		served, err := a.Served()
		if err != nil {
			t.Fatalf("Served() error = %v", err)
		}
		if diff := cmp.Diff([]string{"AssignStaffRole", "Berths", "Moorings", "Surveys", "Tides"}, served.Names()); diff != "" {
			t.Errorf("Names() mismatch (-want +got):\n%s", diff)
		}
		if len(served.Files) != 2 {
			t.Errorf("Files = %q, want both collections", served.Files)
		}
		method, ok := served.Resource("AssignStaffRole")
		if !ok || !method.Takes("Execute") || !method.Takes("Read") || method.Takes("List") {
			t.Errorf("AssignStaffRole = %+v, want what either collection says it takes", method)
		}
		surveys, _ := served.Resource("Surveys")
		if !surveys.Takes("Approve") || !surveys.Takes("Sign") {
			t.Errorf("Surveys = %+v, want what each collection alone says it takes", surveys)
		}
		berths, _ := served.Resource("Berths")
		if !berths.FieldTakes("id", "Read") || !berths.FieldTakes("name", "Update") || !berths.FieldTakes("name", "Delete") || berths.FieldTakes("depth", "Update") || berths.FieldTakes("keel", "Read") {
			t.Errorf("Berths' fields = %v, want what either collection says each takes", berths.Fields)
		}
		if _, ok := served.Resource("Wharves"); ok {
			t.Error("Resource() finds Wharves, which no collection names")
		}
	})

	t.Run("a collection this cannot read is an error", func(t *testing.T) {
		t.Parallel()

		a := discover(t, map[string]string{
			"cmd/generate/resourcegenerator/main.go": strings.Replace(program, "%s", "pkg/router", 1),
			"pkg/router/" + CollectionFileName:       "package router\n",
		})
		if _, err := a.Served(); err == nil {
			t.Error("Served() error = nil for a collection file with no collection")
		}
	})
}

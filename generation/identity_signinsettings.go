package generation

// What every sign-in asks for, in an auth's generated management. Whether everyone is
// asked for a second factor when they sign in, and for how long a browser a person
// asked to be remembered skips it, are two choices an administrator makes in the
// running application, once for the whole auth: the one row of the auth's sign-in
// settings table, which the session library reads at a sign-in. The generator writes,
// for every auth whose schema holds the table, whatever its roles, its password or its
// choice of who may sign up: the declaration over the table, with its change events;
// the store's half (signInSettingsStoreTemplate, joined to the store's template); the
// list the Sign-in page draws the two lines from, and the list the length is picked
// from; and the three methods that make the choices (Require<Auth>SecondFactor,
// StopRequiring<Auth>SecondFactor, which declares a warning and the word a person types,
// and Set<Auth>RememberedBrowsers). An application writes none of it.

// The suffixes of the structs the sign-in settings part of an auth's management
// declares.
const (
	signInSettingRowSuffix = "SessionSignInSetting"
	signInSettingSuffix    = "SignInSetting"
	rememberLengthSuffix   = "RememberLength"
)

// SignInSettingRow is the struct over the auth's sign-in settings table.
func (d *identitySourceData) SignInSettingRow() string { return d.auth + signInSettingRowSuffix }

// SignInSetting is the struct of the auth's sign-in settings as the Sign-in page lists
// them: two lines, each one of the choices in words.
func (d *identitySourceData) SignInSetting() string { return d.auth + signInSettingSuffix }

// RememberLength is the struct of the lengths of time a browser can be remembered for.
func (d *identitySourceData) RememberLength() string { return d.auth + rememberLengthSuffix }

// signInSettingsSources are the source files of the sign-in settings of an instance's
// management: the two lists and the three methods, for every instance whose schema
// holds the table. The setting is every auth's, so every auth has what changes it.
func (r *resourceGenerator) signInSettingsSources(inst *identityInstance) []identitySourceFile {
	needs := []identityTable{identitySignInSettings}

	return []identitySourceFile{
		{dir: inst.methods, name: fileStem(r.pluralize(inst.auth + signInSettingSuffix)), template: identitySignInSettingListTemplate, needs: needs},
		{dir: inst.methods, name: fileStem(r.pluralize(inst.auth + rememberLengthSuffix)), template: identityRememberLengthsTemplate, needs: needs},
		{dir: inst.methods, name: fileStem("Require" + inst.auth + "SecondFactor"), template: identityRequireSecondFactorTemplate, needs: needs},
		{dir: inst.methods, name: fileStem("StopRequiring" + inst.auth + "SecondFactor"), template: identityStopRequiringSecondFactorTemplate, needs: needs},
		{dir: inst.methods, name: fileStem("Set" + inst.auth + "RememberedBrowsers"), template: identitySetRememberedBrowsersTemplate, needs: needs},
	}
}


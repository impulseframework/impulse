// auditText is a part of a row of the audit log as a list's field holds it: nil where
// the row keeps none.
func auditText(text string) *string {
	if text == "" {
		return nil
	}

	return &text
}

// auditAccount is the account a row of the audit log was done to, nil where it was done
// to none.
func auditAccount(row *auditlog.Stored) *impulse.UUID {
	if row.SubjectKind != auditlog.SubjectAccount {
		return nil
	}
	id, err := impulse.UUIDFromString(row.SubjectID)
	if err != nil {
		return nil
	}

	return &id
}

// auditRole is the role a row of the audit log names, by its stored name, nil where it
// names none: the first of them where it names several.
func auditRole(row *auditlog.Stored) *string {
	if len(row.RoleNames) == 0 {
		return nil
	}

	return &row.RoleNames[0]
}

package generation

import "slices"

// Who may sign in without an invitation, in an auth's generated management. Whether a
// sign-in method admits a person with no account and no invitation is one choice an
// administrator makes in the running application, for each method: its row of the
// auth's sign-in methods table, which the session library reads at a sign-in. The
// generator writes, for every auth whose roles the application assigns and whose schema
// holds the table: the declaration over the table, with its change events; the list
// the Sign-in page draws, one row for each method the auth registers, row or no row;
// the two methods that make the choice (Open<Auth>SignUp, which declares a warning and
// the word a person types, and Make<Auth>InviteOnly); and, in an application without
// tenants, the roles a person who signs up may be given, which the default role is
// picked from. An application writes none of it.
//
// In an application with tenants a person who signs up holds no role of the whole
// application: they create a tenant of their own, through the create-your-tenant route,
// which one auth serves (the one whose outlets serve the tenant record). That auth
// carries the choice. Another auth of the same application could give a person who
// signs up nothing, so it carries none, and each of its methods stays invite only.

// The suffixes of the structs the sign-up part of an auth's management declares.
const (
	signInMethodRowSuffix = "SessionSignInMethod"
	signInMethodSuffix    = "SignInMethod"
	signUpRoleSuffix      = "SignUpRole"
)

// SignInMethodRow is the struct over the auth's sign-in methods table.
func (d *identitySourceData) SignInMethodRow() string { return d.auth + signInMethodRowSuffix }

// SignInMethod is the struct of the auth's sign-in methods as the Sign-in page lists
// them: every method the auth registers, with what was chosen for it.
func (d *identitySourceData) SignInMethod() string { return d.auth + signInMethodSuffix }

// SignUpRole is the struct of the roles a person who signs up may be given.
func (d *identitySourceData) SignUpRole() string { return d.auth + signUpRoleSuffix }

// CreatesTenant reports whether a person who signs up creates a tenant of their own:
// the application has a tenant record, so an open method names no default role.
func (d *identitySourceData) CreatesTenant() bool { return d.createsTenant }

// identityCreatesTenant reports whether the instance's auth is the one whose people
// create a tenant of their own: the application has a tenant record, a session outlet
// serves it, and every session outlet that does is bound to this auth. It reads the
// record's outlets off the sources, before the load, and agrees with what the
// create-your-tenant route is generated by after it (tenantCreationServes).
func (r *resourceGenerator) identityCreatesTenant(inst *identityInstance) bool {
	if inst.tenant == nil {
		return false
	}
	served := false
	for _, outlet := range r.allOutlets() {
		if !outlet.servesSessions || !slices.Contains(inst.tenant.outlets, outlet.name) {
			continue
		}
		if outlet.auth == nil || outlet.auth.importPath != inst.importPath {
			return false
		}
		served = true
	}

	return served
}

// choosesSignUp reports whether the instance carries the choice: the application
// assigns the auth's roles, the schema holds the sign-in methods table, and a person
// who signs up gets something, a role of the whole application where there are no
// tenants and a tenant of their own where this auth's people create one. An auth whose
// directory writes the roles has no choice to make.
func (i *identityInstance) choosesSignUp() bool {
	return !i.rolesSynced && i.has(identitySignInMethods) && (i.tenant == nil || i.createsTenant)
}

// signUpSources are the source files of the sign-up part of an instance's management.
func (r *resourceGenerator) signUpSources(inst *identityInstance) []identitySourceFile {
	if !inst.choosesSignUp() {
		return nil
	}
	needs := []identityTable{identitySignInMethods}
	files := []identitySourceFile{
		{dir: inst.methods, name: fileStem(r.pluralize(inst.auth + signInMethodSuffix)), template: identitySignInMethodListTemplate, needs: needs},
		{dir: inst.methods, name: fileStem("Open" + inst.auth + "SignUp"), template: identityOpenSignUpTemplate, needs: needs},
		{dir: inst.methods, name: fileStem("Make" + inst.auth + "InviteOnly"), template: identityMakeInviteOnlyTemplate, needs: needs},
	}
	if inst.tenant == nil {
		files = append(files, identitySourceFile{
			dir: inst.methods, name: fileStem(r.pluralize(inst.auth + signUpRoleSuffix)), template: identitySignUpRolesTemplate, needs: []identityTable{identitySignInMethods, identityMemberships},
		})
	}

	return files
}


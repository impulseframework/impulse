package generation

import "slices"

// Who may sign in without an invitation, in an auth's generated management. Whether a
// sign-in method admits a person with no account and no invitation is one choice an
// administrator makes in the running application, for each method: its row of the
// auth's sign-in methods table, which the session library reads at a sign-in. The
// generator writes, for every auth whose roles the application assigns and whose schema
// holds the table: the declaration over the table, with its change events; the list
// the Sign-in page draws, one row for each method the auth registers, row or no row;
// the two methods that make the choice (Open<Auth>SignUp, which declares a warning and
// the word a person types, and Make<Auth>InviteOnly); and, in an application without
// tenants, the roles a person who signs up may be given, which the default role is
// picked from. An application writes none of it.
//
// The same page carries a second choice, whether a person may ask for a link that
// resets their own password (Set<Auth>SelfServiceReset), which is the password
// method's and not sign-up's: every auth that declares the password method has the
// list and that method, whether or not it carries the choice of who may sign up.
//
// In an application with tenants a person who signs up holds no role of the whole
// application: they create a tenant of their own, through the create-your-tenant route,
// which one auth serves (the one whose outlets serve the tenant record). That auth
// carries the choice. Another auth of the same application could give a person who
// signs up nothing, so it carries none, and each of its methods stays invite only.

// The suffixes of the structs the sign-up part of an auth's management declares.
const (
	signInMethodRowSuffix = "SessionSignInMethod"
	signInMethodSuffix    = "SignInMethod"
	signUpRoleSuffix      = "SignUpRole"
)

// SignInMethodRow is the struct over the auth's sign-in methods table.
func (d *identitySourceData) SignInMethodRow() string { return d.auth + signInMethodRowSuffix }

// SignInMethod is the struct of the auth's sign-in methods as the Sign-in page lists
// them: every method the auth registers, with what was chosen for it.
func (d *identitySourceData) SignInMethod() string { return d.auth + signInMethodSuffix }

// SignUpRole is the struct of the roles a person who signs up may be given.
func (d *identitySourceData) SignUpRole() string { return d.auth + signUpRoleSuffix }

// CreatesTenant reports whether a person who signs up creates a tenant of their own:
// the application has a tenant record, so an open method names no default role.
func (d *identitySourceData) CreatesTenant() bool { return d.createsTenant }

// identityCreatesTenant reports whether the instance's auth is the one whose people
// create a tenant of their own: the application has a tenant record, a session outlet
// serves it, and every session outlet that does is bound to this auth. It reads the
// record's outlets off the sources, before the load, and agrees with what the
// create-your-tenant route is generated by after it (tenantCreationServes).
func (r *resourceGenerator) identityCreatesTenant(inst *identityInstance) bool {
	if inst.tenant == nil {
		return false
	}
	served := false
	for _, outlet := range r.allOutlets() {
		if !outlet.servesSessions || !slices.Contains(inst.tenant.outlets, outlet.name) {
			continue
		}
		if outlet.auth == nil || outlet.auth.importPath != inst.importPath {
			return false
		}
		served = true
	}

	return served
}

// choosesSignUp reports whether the instance carries the choice: the application
// assigns the auth's roles, and a person who signs up gets something, a role of the
// whole application where there are no tenants and a tenant of their own where this
// auth's people create one. An auth whose directory writes the roles has no choice to
// make. Each source of the choice needs the sign-in methods table besides
// (signUpSources), so a schema without it carries none of them.
func (i *identityInstance) choosesSignUp() bool {
	return !i.rolesSynced && (i.tenant == nil || i.createsTenant)
}

// picksDefaultRole reports whether an administrator who opens a method of the instance
// picks the role each new person is given: the instance carries the choice, and the
// application has no tenants. The role is one the opener could give a person directly,
// so the instance's package answers the role file's grants (roleGrantsSource).
func (i *identityInstance) picksDefaultRole() bool {
	return i.choosesSignUp() && i.tenant == nil
}

// judgesRoleChanges reports whether the instance's client is handed the answers of the
// role file's grants on the methods that give a role and take one away: a change to a
// group is judged by them, and so are the default role of a method opened to sign-up
// and the role a tenant is opened to its directory's people with, and the list a
// tenant's role is picked from asks them which roles the caller could give.
// The file is written where the schema holds the tables its part needs
// (roleGrantsSource).
func (i *identityInstance) judgesRoleChanges() bool {
	files := i.roleGrantsSource()
	for _, file := range files {
		if slices.ContainsFunc(file.needs, func(kind identityTable) bool { return !i.has(kind) }) {
			return false
		}
	}

	return len(files) > 0
}

// JudgesRoleChanges reports whether the instance's client is handed the role file's
// answers on giving a role and taking one away (grants.go).
func (d *identitySourceData) JudgesRoleChanges() bool { return d.judgesRoleChanges() }

// roleGrantsSource is the source file of the answers the rules ask of the role file
// (grants.go), by the grants of the methods that give a role and take one away: one
// file, for an instance that keeps groups, whose changes are judged as the role changes
// they make, for one whose administrator picks the default role of an open method, for
// one whose tenant's administrator picks the role everyone from the tenant's directory
// gets (seatsDirectory), for one whose tenant gives roles by hand, where the list a
// role is picked from offers the roles the caller could give (picksRoles), for one whose
// people take a role for a set time, which is judged as the role given directly
// (takesRoles), and for every one whose roles the application gives, whose whole
// application's role fields pick from the roles the caller could give
// (givableRoleSources).
func (i *identityInstance) roleGrantsSource() []identitySourceFile {
	var needs []identityTable
	switch {
	case i.keepsGroups():
		needs = append(append(identityGroupTables(), identityUsers), identityMemberships)
	case !i.rolesSynced:
		// Every other reason is an instance whose roles the application gives:
		// picksDefaultRole, seatsDirectory, picksRoles and takesRoles each hold only
		// there. A role taken for a set time is judged as the same role given directly.
		needs = []identityTable{identityMemberships}
	default:
		return nil
	}

	return []identitySourceFile{{dir: i.methods, name: "grants", template: identityGrantsTemplate, needs: needs}}
}

// signUpSources are the source files of the Sign-in page of an instance's management:
// the list of the auth's sign-in methods, and what an administrator chooses over it.
// Two things are chosen there, each where the instance has it to choose. Who may sign
// up (the method that opens a sign-in method and the one that makes it invite only
// again, and without tenants the roles a default role is picked from) is chosen by an
// instance that carries the choice (choosesSignUp). Whether people reset their own
// password is chosen by every instance that declares the password method, whether or
// not it carries the other choice: an auth whose people join a tenant somebody else
// made has passwords to reset like any other. An instance with neither has no page.
func (r *resourceGenerator) signUpSources(inst *identityInstance) []identitySourceFile {
	chooses := inst.choosesSignUp()
	if !chooses && !inst.password {
		return nil
	}
	needs := []identityTable{identitySignInMethods}
	files := []identitySourceFile{
		{dir: inst.methods, name: fileStem(r.pluralize(inst.auth + signInMethodSuffix)), template: identitySignInMethodListTemplate, needs: needs},
	}
	if chooses {
		files = append(files,
			identitySourceFile{dir: inst.methods, name: fileStem("Open" + inst.auth + "SignUp"), template: identityOpenSignUpTemplate, needs: needs},
			identitySourceFile{dir: inst.methods, name: fileStem("Make" + inst.auth + "InviteOnly"), template: identityMakeInviteOnlyTemplate, needs: needs},
		)
	}
	// Only an auth that declares the password method has a password to reset.
	if inst.password {
		files = append(files, identitySourceFile{dir: inst.methods, name: fileStem("Set" + inst.auth + "SelfServiceReset"), template: identitySetSelfServiceResetTemplate, needs: needs})
	}
	if chooses && inst.tenant == nil {
		files = append(files, identitySourceFile{
			dir: inst.methods, name: fileStem(r.pluralize(inst.auth + signUpRoleSuffix)), template: identitySignUpRolesTemplate, needs: []identityTable{identitySignInMethods, identityMemberships},
		})
	}

	return files
}


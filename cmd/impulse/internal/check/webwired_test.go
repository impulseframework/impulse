// webSiteProgram renders a site's generator program under the generated router: its
// default outlet bound to the auth and serving a browser application at the root, with
// the generated client in the site's workspace.
func webSiteProgram(site, auth string) string {
	return program("apps/"+site+"/pkg/resources",
		`generation.GenerateHandlers("apps/`+site+`/app"),`,
		`generation.GenerateRouter(),`,
		`generation.GenerateRoutes("apps/`+site+`/pkg/router", "api", generation.Auth("example.com/harbor/pkg/auth/`+auth+`", generation.PasswordMethod()), generation.WebApp("/")),`,
		`generation.GenerateTypescript("apps/`+site+`/web/`+site+`/src/app/core/service"),`,
	)
}

// webAngular renders a site's workspace configuration: one project named for the site.
func webAngular(site string) string {
	return `{"projects": {"` + site + `": {"root": "` + site + `", "sourceRoot": "` + site + `/src"}}}` + "\n"
}

// webConstants renders the generated constants exporting the resources of the auth's
// generated management.
func webConstants(auth string) string {
	return "// Code generated by resourcegeneration. DO NOT EDIT.\nimport { Method, Resource } from '@impulseframework/resource';\n\nexport const Resources = {\n" +
		"  FeatureFlags: 'FeatureFlags' as Resource,\n" +
		"  " + auth + "SessionUsers: '" + auth + "SessionUsers' as Resource,\n" +
		"  " + auth + "Sessions: '" + auth + "Sessions' as Resource,\n" +
		"  " + auth + "UserRoles: '" + auth + "UserRoles' as Resource,\n" +
		"};\n\nexport const Methods = {\n  Create" + auth + "User: 'Create" + auth + "User' as Method,\n};\n"
}

// webPeoplePage renders a page of the application's own over the auth's people: the
// accounts and the roles they hold, taken from the generated constants.
func webPeoplePage(auth string) string {
	return "import { Component } from '@angular/core';\nimport { Permissions, Resources } from '@app/service/zz_gen_constants';\n\nexport class PeopleComponent {\n" +
		"  readonly scope = { resource: Resources." + auth + "SessionUsers, permission: Permissions.List };\n" +
		"  readonly roles = { resource: Resources." + auth + "UserRoles, permission: Permissions.List };\n}\n"
}

// webAPI renders the generated API description carrying the auth's generated management
// with the sides named, or none of any auth when no side is.
func webAPI(auth string, scopes ...string) string {
	identity := ""
	if len(scopes) > 0 {
		identity = "  identity: [\n    {\n      auth: '" + auth + "',\n      label: '" + auth + "',\n      sides: [\n"
		for _, scope := range scopes {
			identity += "        {\n          scope: '" + scope + "',\n          lists: { users: Resources." + auth + "SessionUsers },\n          methods: { create: Methods.Create" + auth + "User },\n        },\n"
		}
		identity += "      ],\n    },\n  ],\n"
	}

	return "// Code generated by resourcegeneration. DO NOT EDIT.\nexport const apiDescriptor: ApiDescriptor = {\n  methods: {\n    [Methods.SetFeature]: { method: Methods.SetFeature, scope: 'global' },\n  },\n" + identity + "};\n"
}

// webRoutes renders routes asking the library for the pages of the auth's management:
// the whole application's side on one line, and the tenant's as a formatter lays a long
// call out, when asked for.
func webRoutes(auth string, tenant bool) string {
	routes := "import { identityRoutes } from '@impulseframework/resource-angular/identity-pages';\n\nexport const routes: Routes = [\n" +
		"  // The pages are asked for by identityRoutes(apiDescriptor, resourceMeta, { auth: 'Nobody', scope: 'global' }).\n" +
		"  ...identityRoutes(apiDescriptor, resourceMeta, { auth: '" + auth + "', scope: 'global' }),\n"
	if tenant {
		routes += "  ...identityRoutes(apiDescriptor, resourceMeta, {\n    auth: '" + auth + "',\n    scope: 'domain',\n  }).map(underTenant),\n"
	}

	return routes + "];\n"
}

// webAppConfig renders an application configuration whose HttpClient names the cookie.
func webAppConfig(cookie string) string {
	return "import { provideHttpClient, withInterceptors, withXsrfConfiguration } from '@angular/common/http';\n\nexport const appConfig = {\n  providers: [\n" +
		"    provideHttpClient(withInterceptors([apiVersionInterceptor]), withXsrfConfiguration({ cookieName: '" + cookie + "' })),\n  ],\n};\n"
}

// webAuth renders an auth package constructing its session Auth, naming its XSRF cookie
// as the skeleton's auths do (XSRFCookie, Name + "-xsrf") or leaving it to the library.
func webAuth(name string, namesCookie bool) string {
	option := ""
	if namesCookie {
		option = ", session.WithXSRFCookieName(XSRFCookie)"
	}

	return `package ` + name + `

import (
	"context"

	cloudspanner "cloud.google.com/go/spanner"
	"github.com/impulseframework/impulse/session"
	"github.com/impulseframework/impulse/session/sessionstorage"
)

const (
	Name        = "` + name + `"
	TablePrefix = "` + pascal(name) + `"
	XSRFCookie  = Name + "-xsrf"
)

type Auth struct {
	session *session.Auth[session.NoCustomData, session.NoCustomData, *cloudspanner.ReadWriteTransaction]
}

func New(ctx context.Context, db *cloudspanner.Client, key string) (*Auth, error) {
	s, err := session.NewAuth[session.NoCustomData, session.NoCustomData](sessionstorage.NewSpannerAuth(db), key,
		session.WithSessionTableName(TablePrefix+"Sessions")` + option + `)
	if err != nil {
		return nil, err
	}
	session.PasswordSignIn(s)

	return &Auth{session: s}, nil
}
`
}

// webSite lays out one site: its program bound to the auth, its workspace, the generated
// constants and API description of the auth, and a page, routes and an application
// configuration naming the page's auth and the cookie.
func webSite(files map[string]string, site, auth, pageAuth, cookie string) {
	web := "apps/" + site + "/web/"
	files["cmd/generate/"+site+"/main.go"] = webSiteProgram(site, auth)
	files[web+"angular.json"] = webAngular(site)
	files[web+site+"/src/app/core/service/zz_gen_constants.ts"] = webConstants(pascal(auth))
	files[web+site+"/src/app/core/service/zz_gen_api.ts"] = webAPI(pascal(auth), "global")
	files[web+site+"/src/app/components/ui/people/people.component.ts"] = webPeoplePage(pascal(pageAuth))
	files[web+site+"/src/app/app.routes.ts"] = webRoutes(pascal(pageAuth), false)
	files[web+site+"/src/app/app.config.ts"] = webAppConfig(cookie)
}

func TestWebWired(t *testing.T) {
	t.Parallel()

	const (
		portalPeople = "apps/portal/web/portal/src/app/components/ui/people/people.component.ts"
		portalRoutes = "apps/portal/web/portal/src/app/app.routes.ts"
		portalConfig = "apps/portal/web/portal/src/app/app.config.ts"
		portalAPI    = "apps/portal/web/portal/src/app/core/service/zz_gen_api.ts"
		consoleLine  = "console: apps/console/web/console/src names 2 resource(s) its generated client exports, asks for the pages of the management of Staff, and names the staff auth's XSRF cookie (staff-xsrf)"
		portalLine   = "portal: apps/portal/web/portal/src names 2 resource(s) its generated client exports, asks for the pages of the management of Members, and names the members auth's XSRF cookie (members-xsrf)"
	)
	auths := map[string]string{
		"pkg/auth/staff/staff.go":     webAuth("staff", true),
		"pkg/auth/members/members.go": webAuth("members", true),
	}
	// bound is the sites layout with each site's browser application bound to its auth.
	bound := func() map[string]string {
		files := map[string]string{}
		for rel, content := range auths {
			files[rel] = content
		}
		webSite(files, "console", "staff", "staff", "staff-xsrf")
		webSite(files, "portal", "members", "members", "members-xsrf")

		return files
	}
	// stale is the sites layout after the portal's outlet was bound to the members auth
	// while its browser application, the console's copy, still names the staff auth.
	stale := func() map[string]string {
		files := bound()
		webSite(files, "portal", "members", "staff", "staff-xsrf")

		return files
	}
	// flat is the flat layout with two browser projects in one workspace: the console on
	// the default outlet with the staff auth, the portal outlet with the members auth.
	flat := func() map[string]string {
		files := map[string]string{}
		for rel, content := range auths {
			files[rel] = content
		}
		files["cmd/generate/main.go"] = program("pkg/resources",
			`generation.GenerateHandlers("app"),`,
			`generation.GenerateRouter(),`,
			`generation.GenerateRoutes("pkg/router", "console/api", generation.Auth("example.com/harbor/pkg/auth/staff", generation.PasswordMethod()), generation.WebApp("/console")),`,
			`generation.WithRouterOutlet("portal", "portal/api", generation.Auth("example.com/harbor/pkg/auth/members", generation.PasswordMethod()), generation.WebApp("/portal")),`,
			`generation.GenerateTypescript("web/console/src/app/core/service"),`,
			`generation.GenerateTypescript("web/portal/src/app/core/service", generation.ForOutlet("portal")),`,
		)
		files["web/angular.json"] = `{"projects": {"console": {"root": "console", "sourceRoot": "console/src"}, "portal": {"root": "portal", "sourceRoot": "portal/src"}}}` + "\n"
		files["web/console/src/app/core/service/zz_gen_constants.ts"] = webConstants("Staff")
		files["web/console/src/app/components/ui/people/people.component.ts"] = webPeoplePage("Staff")
		files["web/console/src/app/app.config.ts"] = webAppConfig("staff-xsrf")
		files["web/portal/src/app/core/service/zz_gen_constants.ts"] = webConstants("Members")
		files["web/portal/src/app/components/ui/people/people.component.ts"] = webPeoplePage("Members")
		files["web/portal/src/app/app.config.ts"] = webAppConfig("members-xsrf")

		return files
	}

	tests := []struct {
		name        string
		files       map[string]string
		edit        func(files map[string]string)
		wantStatus  Status
		wantSummary string
		wantDetails []string
	}{
		{
			name:        "two sites bound to their auths",
			files:       bound(),
			wantStatus:  Pass,
			wantSummary: "2 browser application(s) bound to their outlets' auths",
			wantDetails: []string{consoleLine, portalLine},
		},
		{
			name:        "a site's copy of the console's browser application still names the console's auth",
			files:       stale(),
			wantStatus:  Fail,
			wantSummary: "4 browser binding problem(s)",
			wantDetails: []string{
				portalRoutes + ":5: identityRoutes asks the library for the pages of the Staff auth's management, which " + portalAPI + ", the portal outlet's API description, does not carry (it carries the management of Members), so the library refuses the request when the application loads, which no build sees; name an auth it carries (auth: 'Members'), as impulse add auth --outlet portal writes the site's routes",
				portalPeople + ":5: Resources.StaffSessionUsers is not exported by apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts, the portal outlet's generated client, so the browser build fails on it; rename it to a resource the client exports (the members auth's are MembersSessionUsers, MembersSessions, MembersUserRoles)",
				portalPeople + ":6: Resources.StaffUserRoles is not exported by apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts, the portal outlet's generated client, so the browser build fails on it; rename it to a resource the client exports (the members auth's are MembersSessionUsers, MembersSessions, MembersUserRoles)",
				portalConfig + ":5: withXsrfConfiguration names the cookie staff-xsrf, which no auth bound to the portal outlet issues (the members auth issues members-xsrf), so the server refuses every mutating request; name members-xsrf, as impulse add auth --outlet portal writes it",
			},
		},
		{
			name:  "a site whose program generates no management asks for none",
			files: bound(),
			edit: func(files map[string]string) {
				files[portalAPI] = webAPI("Members")
			},
			wantStatus:  Fail,
			wantSummary: "1 browser binding problem(s)",
			wantDetails: []string{
				portalRoutes + ":5: identityRoutes asks the library for the pages of the Members auth's management, which " + portalAPI + ", the portal outlet's API description, does not carry (it carries no auth's management), so the library refuses the request when the application loads, which no build sees; the portal outlet's program generates none (generation.GenerateIdentity): take the request out, or have the program generate the management and run go generate ./...",
			},
		},
		{
			name:  "a tenant's pages are asked of a description that carries the tenant's side",
			files: bound(),
			edit: func(files map[string]string) {
				files[portalRoutes] = webRoutes("Members", true)
			},
			wantStatus:  Fail,
			wantSummary: "1 browser binding problem(s)",
			wantDetails: []string{
				portalRoutes + ":6: identityRoutes asks the library for the tenant's side of the Members auth's management (scope: 'domain'), which " + portalAPI + ", the portal outlet's API description, does not carry (it carries: global), so the library refuses the request when the application loads, which no build sees; ask for a side it carries",
			},
		},
		{
			name:  "both sides asked of a description that carries both",
			files: bound(),
			edit: func(files map[string]string) {
				files[portalRoutes] = webRoutes("Members", true)
				files[portalAPI] = webAPI("Members", "global", "domain")
			},
			wantStatus:  Pass,
			wantSummary: "2 browser application(s) bound to their outlets' auths",
			wantDetails: []string{consoleLine, portalLine},
		},
		{
			name:  "a client predating the outlet's binding is regenerated, not renamed around",
			files: bound(),
			edit: func(files map[string]string) {
				files["apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts"] = webConstants("Staff")
			},
			wantStatus:  Fail,
			wantSummary: "2 browser binding problem(s)",
			wantDetails: []string{
				portalPeople + ":5: Resources.MembersSessionUsers is not exported by apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts, the portal outlet's generated client, so the browser build fails on it; the client exports no resource of the auth bound to the portal outlet, so it predates the binding: run go generate ./...",
				portalPeople + ":6: Resources.MembersUserRoles is not exported by apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts, the portal outlet's generated client, so the browser build fails on it; the client exports no resource of the auth bound to the portal outlet, so it predates the binding: run go generate ./...",
			},
		},
		{
			name:  "a client not generated yet has the cookie checked alone",
			files: stale(),
			edit: func(files map[string]string) {
				delete(files, "apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts")
				delete(files, portalAPI)
			},
			wantStatus:  Fail,
			wantSummary: "1 browser binding problem(s)",
			wantDetails: []string{
				portalConfig + ":5: withXsrfConfiguration names the cookie staff-xsrf, which no auth bound to the portal outlet issues (the members auth issues members-xsrf), so the server refuses every mutating request; name members-xsrf, as impulse add auth --outlet portal writes it",
			},
		},
		{
			name:  "a hand-written router declares no auth, so any auth's cookie is the outlet's",
			files: bound(),
			edit: func(files map[string]string) {
				files["cmd/generate/portal/main.go"] = program("apps/portal/pkg/resources",
					`generation.GenerateHandlers("apps/portal/app"),`,
					`generation.GenerateRoutes("apps/portal/pkg/router", "api", generation.WebApp("/")),`,
					`generation.GenerateTypescript("apps/portal/web/portal/src/app/core/service"),`,
				)
			},
			wantStatus:  Pass,
			wantSummary: "2 browser application(s) bound to their outlets' auths",
			wantDetails: []string{consoleLine, portalLine},
		},
		{
			name:  "an auth naming no XSRF cookie issues the library's default",
			files: bound(),
			edit: func(files map[string]string) {
				files["pkg/auth/staff/staff.go"] = webAuth("staff", false)
			},
			wantStatus:  Fail,
			wantSummary: "1 browser binding problem(s)",
			wantDetails: []string{
				"apps/console/web/console/src/app/app.config.ts:5: withXsrfConfiguration names the cookie staff-xsrf, which no auth bound to the console outlet issues (the staff auth issues XSRF-TOKEN), so the server refuses every mutating request; name XSRF-TOKEN, as impulse add auth --outlet console writes it",
			},
		},
		{
			name:        "the flat layout's projects are read against their outlets",
			files:       flat(),
			wantStatus:  Pass,
			wantSummary: "2 browser application(s) bound to their outlets' auths",
			wantDetails: []string{"harbor: web/console/src names 2 resource(s) its generated client exports and the staff auth's XSRF cookie (staff-xsrf); web/portal/src names 2 resource(s) its generated client exports and the members auth's XSRF cookie (members-xsrf)"},
		},
		{
			name:  "no browser project is bound to a session outlet",
			files: bound(),
			edit: func(files map[string]string) {
				for _, site := range []string{"console", "portal"} {
					delete(files, "apps/"+site+"/web/angular.json")
				}
			},
			wantStatus:  Skip,
			wantSummary: "no browser project is bound to a session outlet",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			if tt.edit != nil {
				tt.edit(tt.files)
			}
			root := t.TempDir()
			write := func(rel, content string) {
				t.Helper()
				if err := os.MkdirAll(filepath.Dir(filepath.Join(root, rel)), 0o750); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(filepath.Join(root, rel), []byte(content), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			write("go.mod", "module example.com/harbor\n\ngo 1.26.6\n")
			for rel, content := range tt.files {
				write(rel, content)
			}

			a, err := app.Discover(root)
			if err != nil {
				t.Fatalf("app.Discover() error = %v", err)
			}
			got := webWired{}.Run(context.Background(), &Env{App: a})
			want := Result{Name: webWired{}.Name(), Status: tt.wantStatus, Summary: tt.wantSummary, Details: tt.wantDetails}
			if diff := cmp.Diff(want, got); diff != "" {
				t.Errorf("Run() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

func TestWebWiredMeaning(t *testing.T) {
	t.Parallel()

	meaning := webWired{}.Meaning()
	for _, want := range []string{"identityRoutes(apiDescriptor, resourceMeta, { auth: '<Auth>', scope: 'global' })", "Resources.<Name>", "withXsrfConfiguration({ cookieName: '<auth>-xsrf' })", "TS2339", "impulse add auth --outlet <site>"} {
		if !strings.Contains(meaning, want) {
			t.Errorf("Meaning() lacks %q", want)
		}
	}
}

package check

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/google/go-cmp/cmp"

	"github.com/impulseframework/impulse/app"
)

func TestRolesFileAccepted(t *testing.T) {
	t.Parallel()

	// The role files under testdata/rolesfile: one the engine accepts, one naming a role
	// outside the grammar, and one whose role carries an empty description.
	fixture := func(name string) string {
		t.Helper()
		data, err := os.ReadFile(filepath.Join("testdata", "rolesfile", name))
		if err != nil {
			t.Fatal(err)
		}

		return string(data)
	}
	withRoles := func(roles string) map[string]string {
		return map[string]string{
			"pkg/auth/staff/staff.go":   staffAuth,
			"pkg/auth/staff/roles.json": roles,
			"pkg/config/data.go":        staffConfig,
			"app/app.go":                staffApp,
		}
	}

	// An application whose generator writes routes, with the collection file the
	// generator wrote beside them: collection is the file's text, empty for a generator
	// that has not written one yet.
	withCollection := func(roles, collection string) map[string]string {
		files := withRoles(roles)
		files["cmd/generate/main.go"] = program("pkg/resources", `generation.GenerateHandlers("app"),`, `generation.GenerateRoutes("pkg/router", "api"),`)
		files["pkg/router/zz_gen_collection.go"] = collection

		return files
	}
	const (
		// harborCollection marks CreateHarbor an action no role is given, as the
		// generator writes the action of the create-your-tenant route, beside an action
		// a role is given.
		harborCollection = `// Code generated by resourcegeneration. DO NOT EDIT.

package router

import (
	"github.com/impulseframework/impulse/accesstypes"
	"github.com/impulseframework/impulse/resource"
)

const ClassAccess accesstypes.ActionClass = "access"

func Collection() *resource.GeneratedCollection {
	return resource.MustNewGeneratedCollection(resource.CollectionData{
		Resources: []resource.CollectionResource{
			{
				Name:        "CreateHarbor",
				Scope:       accesstypes.GlobalPermissionScope,
				Permissions: []accesstypes.Permission{accesstypes.Execute},
				Classes:     []accesstypes.ActionClass{ClassAccess},
				NoRole:      true,
			},
			{
				Name:        "Launch",
				Scope:       accesstypes.GlobalPermissionScope,
				Permissions: []accesstypes.Permission{accesstypes.Execute},
			},
		},
	})
}
`
		founder   = `{"roles": {"global": [{"name": "Founder", "description": "Opens a harbor.", "permissions": {"Execute": [{"resource": "Launch"}, {"resource": "CreateHarbor"}]}}], "domain": [{"name": "Pilot", "description": "Brings ships in.", "permissions": {"Read": [{"resource": "CreateHarbor"}]}}]}}`
		launcher  = `{"roles": {"global": [{"name": "Launcher", "description": "Launches ships.", "permissions": {"Execute": [{"resource": "Launch"}]}}], "domain": []}}`
		whyNoRole = "which is an action no role is given (pkg/router/zz_gen_collection.go writes it with NoRole: true): nothing asks for a grant of it, so the grant would do nothing, and the action is registered only so that a permission mask can refuse it to a session that acts as someone; remove the grant from the role"
	)

	tests := []struct {
		name        string
		files       map[string]string
		wantStatus  Status
		wantSummary string
		wantDetails []string
	}{
		{
			name: "a grant of an action no role is given", files: withCollection(founder, harborCollection),
			wantStatus: Fail, wantSummary: "1 role file(s) the permission engine would refuse at start",
			wantDetails: []string{
				"pkg/auth/staff/roles.json: role Founder grants Execute on CreateHarbor, " + whyNoRole,
				"pkg/auth/staff/roles.json: role Pilot grants Read on CreateHarbor, " + whyNoRole,
			},
		},
		{
			name: "a file that grants the actions a role is given, beside an action no role is given", files: withCollection(launcher, harborCollection),
			wantStatus: Pass, wantSummary: "1 role file(s) parse the way the permission engine reads them: pkg/auth/staff/roles.json",
		},
		{
			name: "the name where the collection does not mark it is the engine's to judge", files: withCollection(founder, strings.Replace(harborCollection, "\t\t\t\tNoRole:      true,\n", "", 1)),
			wantStatus: Pass, wantSummary: "1 role file(s) parse the way the permission engine reads them: pkg/auth/staff/roles.json",
		},
		{
			name: "a generator that has written no collection file marks nothing", files: withCollection(founder, ""),
			wantStatus: Pass, wantSummary: "1 role file(s) parse the way the permission engine reads them: pkg/auth/staff/roles.json",
		},
		{
			name: "a collection file that does not parse", files: withCollection(launcher, "package router\n\nfunc Collection() {\n"),
			wantStatus: Fail, wantSummary: "pkg/router/zz_gen_collection.go does not parse, so the actions no role is given cannot be read from it: pkg/router/zz_gen_collection.go:3:21: expected '}', found 'EOF'; regenerate the application (go generate ./...)",
		},
		{
			name: "a file the engine accepts", files: withRoles(fixture("good.json")),
			wantStatus: Pass, wantSummary: "1 role file(s) parse the way the permission engine reads them: pkg/auth/staff/roles.json",
		},
		{
			name: "an empty file, as add auth writes it", files: withRoles(rolesJSON),
			wantStatus: Pass, wantSummary: "1 role file(s) parse the way the permission engine reads them: pkg/auth/staff/roles.json",
		},
		{
			name: "a role named with an underscore", files: withRoles(fixture("underscore.json")),
			wantStatus: Fail, wantSummary: "1 role file(s) the permission engine would refuse at start",
			wantDetails: []string{"pkg/auth/staff/roles.json: role Administrator_Global: a role name is letters and digits starting with a capital letter, such as Administrator or TenantAdministrator; the scope is never part of the name"},
		},
		{
			name:       "a role taking the name of the framework's role",
			files:      withRoles(`{"roles": {"global": [{"name": "SuperAdministrator", "description": "Runs the application.", "permissions": {}}]}}`),
			wantStatus: Fail, wantSummary: "1 role file(s) the permission engine would refuse at start",
			wantDetails: []string{"pkg/auth/staff/roles.json: role SuperAdministrator: the name is reserved: every auth has the Super Administrator role, which the framework defines, and an application defines no role of that name; remove it from the global roles and give what it grants to a role of another name"},
		},
		{
			name:       "a tenant role taking the name in another case",
			files:      withRoles(`{"roles": {"domain": [{"name": "Superadministrator", "description": "Runs one tenant.", "permissions": {}}]}}`),
			wantStatus: Fail, wantSummary: "1 role file(s) the permission engine would refuse at start",
			wantDetails: []string{"pkg/auth/staff/roles.json: role Superadministrator: the name is reserved: every auth has the Super Administrator role, which the framework defines, and an application defines no role of that name; remove it from the domain roles and give what it grants to a role of another name"},
		},
		{
			name: "a role with an empty description", files: withRoles(fixture("undescribed.json")),
			wantStatus: Fail, wantSummary: "1 role file(s) the permission engine would refuse at start",
			wantDetails: []string{"pkg/auth/staff/roles.json: role Auditor: a role carries a description, one or two plain sentences saying what the role is for"},
		},
		{
			name: "a file that is not JSON", files: withRoles("{\"roles\": {\"global\": [}\n"),
			wantStatus: Fail, wantSummary: "1 role file(s) the permission engine would refuse at start",
			wantDetails: []string{"pkg/auth/staff/roles.json: the role file does not parse: invalid character '}' looking for beginning of value"},
		},
		{
			name: "the role file is missing", files: withRoles(""),
			wantStatus: Fail, wantSummary: "1 role file(s) the permission engine would refuse at start",
			wantDetails: []string{"pkg/auth/staff/roles.json does not exist; the staff auth embeds its role file from there"},
		},
		{
			name: "no auth package", files: map[string]string{"pkg/config/doc.go": "package config\n"},
			wantStatus: Skip, wantSummary: "no auth package (pkg/auth/<name>) holds a role file",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			root := t.TempDir()
			write := func(rel, content string) {
				t.Helper()
				if err := os.MkdirAll(filepath.Dir(filepath.Join(root, rel)), 0o750); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(filepath.Join(root, rel), []byte(content), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			write("go.mod", "module example.com/harbor\n\ngo 1.26.6\n")
			for rel, content := range tt.files {
				if content == "" {
					continue
				}
				write(rel, content)
			}
			a, err := app.Discover(root)
			if err != nil {
				t.Fatalf("app.Discover() error = %v", err)
			}
			got := rolesFileAccepted{}.Run(context.Background(), &Env{App: a})
			want := Result{Name: "roles-file", Status: tt.wantStatus, Summary: tt.wantSummary, Details: tt.wantDetails}
			if diff := cmp.Diff(want, got); diff != "" {
				t.Errorf("Run() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

// The generated list of a package that stores a secret, and of one that stores none.
const (
	holdersStoring = "// Code generated by resourcegeneration. DO NOT EDIT.\n\npackage %s\n\nimport \"github.com/impulseframework/impulse/resource\"\n\nfunc SecretHolders() []resource.SecretHolder {\n\treturn []resource.SecretHolder{\n\t\tresource.SecretHolderOf[Beacon](),\n\t}\n}\n"
	holdersNone    = "// Code generated by resourcegeneration. DO NOT EDIT.\n\npackage %s\n\nimport \"github.com/impulseframework/impulse/resource\"\n\nfunc SecretHolders() []resource.SecretHolder {\n\treturn nil\n}\n"
)

// deployFile is a deploy package that retires a version, with the given imports beside
// the library's and the given body of the function that does it.
func deployFile(imports, body string) string {
	return "package deploy\n\nimport (\n\t\"context\"\n\n\t\"github.com/impulseframework/impulse/resource\"\n" + imports + ")\n\n" +
		"func RetireSecret(ctx context.Context, client resource.Client, variable string, handed ...resource.SecretHolder) error {\n" + body + "\n\treturn err\n}\n"
}

// TestSecretHolders runs the check on an application with two resources packages that
// carry generated secret holders, one storing a secret and one storing none, and a deploy
// package that retires a version. The retirement reads only the packages its call is
// handed, so the check passes when the call names both, however it joins them, and fails
// naming the package left out, a call whose holders it cannot read, and an application
// no code retires.
func TestSecretHolders(t *testing.T) {
	t.Parallel()

	const (
		resources = "\t\"example.com/lighthouse/pkg/resources\"\n"
		shared    = "\t\"example.com/lighthouse/pkg/sharedresources\"\n"
		aliased   = "\tkept \"example.com/lighthouse/pkg/sharedresources\"\n"
		slicesPkg = "\t\"slices\"\n"
		argument  = "slices.Concat(pkg/resources.SecretHolders(), pkg/sharedresources.SecretHolders())..."
		// The package that stores a secret left out, and the one that stores none.
		notHanded = "pkg/deploy/deploy.go:<call>: resource.RetireSecretVersion is not handed example.com/lighthouse/pkg/resources.SecretHolders(), so a retirement never reads the secrets that package stores and still reports the version retired; pass every resources package's generated list in the call: " + argument
		notEmpty  = "pkg/deploy/deploy.go:<call>: resource.RetireSecretVersion is not handed example.com/lighthouse/pkg/sharedresources.SecretHolders(), so a secret that package comes to store would never be read by a retirement (its list is empty today); pass every resources package's generated list in the call: " + argument
		unread    = "pkg/deploy/deploy.go:<call>: resource.RetireSecretVersion takes holders from where they cannot be read here (a parameter, a function of the application's own, or a list written by hand), so whether every package is among them is not known; name each package's generated SecretHolders() in the call: " + argument
		passed    = "2 package(s) with generated secret holders, each handed to the retirement at pkg/deploy/deploy.go:<call>"
	)
	name := secretHolders{}.Name()
	tests := []struct {
		name string
		// deploy is pkg/deploy/deploy.go, empty for an application with no deploy
		// package; noHolders leaves the generated lists out.
		deploy    string
		noHolders bool
		// test is a test file of the deploy package, which the check does not read.
		test string
		// want is the result, with <call> for the line of the retirement call.
		want Result
	}{
		{
			name:   "both packages joined in the call",
			deploy: deployFile(resources+shared+slicesPkg, "\t_, err := resource.RetireSecretVersion(ctx, client, variable, slices.Concat(resources.SecretHolders(), sharedresources.SecretHolders())...)"),
			want:   pass(name, passed),
		},
		{
			name:   "both packages through a variable of the function, one appended, one under another import name",
			deploy: deployFile(resources+aliased, "\tholders := resources.SecretHolders()\n\tholders = append(holders, kept.SecretHolders()...)\n\t_, err := resource.RetireSecretVersion(ctx, client, variable, holders...)"),
			want:   pass(name, passed),
		},
		{
			name:   "a package left out is named, though it stores no secret today",
			deploy: deployFile(resources, "\t_, err := resource.RetireSecretVersion(ctx, client, variable, resources.SecretHolders()...)"),
			want:   fail(name, "1 problem(s) with the secret holders a retirement is handed", notEmpty),
		},
		{
			name:   "the package that stores the secret left out is named",
			deploy: deployFile(shared, "\t_, err := resource.RetireSecretVersion(ctx, client, variable, sharedresources.SecretHolders()...)"),
			want:   fail(name, "1 problem(s) with the secret holders a retirement is handed", notHanded),
		},
		{
			name:   "holders passed in by the caller cannot be read",
			deploy: deployFile("", "\t_, err := resource.RetireSecretVersion(ctx, client, variable, handed...)"),
			want:   fail(name, "3 problem(s) with the secret holders a retirement is handed", notHanded, notEmpty, unread),
		},
		{
			name:   "a list written by hand beside a generated one cannot be read",
			deploy: deployFile(resources+shared, "\t_, err := resource.RetireSecretVersion(ctx, client, variable, append(sharedresources.SecretHolders(), resource.SecretHolderOf[resources.Beacon]())...)"),
			want:   fail(name, "2 problem(s) with the secret holders a retirement is handed", notHanded, unread),
		},
		{
			name: "no code retires a version",
			want: fail(name, "no code retires a version of the application secret", "resource.RetireSecretVersion is called nowhere outside tests, so the stored secrets of example.com/lighthouse/pkg/resources, example.com/lighthouse/pkg/sharedresources are never written under a new version and no version can be disabled: call it from the deploy package with "+argument+", and run it from the migrate command's -retire-secret flag, as a skeleton's pkg/deploy and cmd/deployment/migrate do"),
		},
		{
			name: "a call in a test retires nothing",
			test: "package deploy\n\nimport (\n\t\"context\"\n\t\"testing\"\n\n\t\"example.com/lighthouse/pkg/resources\"\n\t\"github.com/impulseframework/impulse/resource\"\n)\n\nfunc TestRetire(t *testing.T) {\n\t_, _ = resource.RetireSecretVersion(context.Background(), nil, \"\", resources.SecretHolders()...)\n}\n",
			want: fail(name, "no code retires a version of the application secret", "resource.RetireSecretVersion is called nowhere outside tests, so the stored secrets of example.com/lighthouse/pkg/resources, example.com/lighthouse/pkg/sharedresources are never written under a new version and no version can be disabled: call it from the deploy package with "+argument+", and run it from the migrate command's -retire-secret flag, as a skeleton's pkg/deploy and cmd/deployment/migrate do"),
		},
		{
			name:      "an application with no generated holders is not judged",
			noHolders: true,
			deploy:    deployFile("", "\t_, err := resource.RetireSecretVersion(ctx, client, variable, handed...)"),
			want:      skip(name, "no resources package carries generated secret holders (zz_gen_secret_holders.go)"),
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			if err := os.CopyFS(dir, os.DirFS(filepath.Join("..", "..", "..", "..", "app", "testdata", "flat"))); err != nil {
				t.Fatalf("copy fixture: %v", err)
			}
			files := map[string]string{}
			if !tt.noHolders {
				files["pkg/resources/zz_gen_secret_holders.go"] = fmt.Sprintf(holdersStoring, "resources")
				files["pkg/sharedresources/zz_gen_secret_holders.go"] = fmt.Sprintf(holdersNone, "sharedresources")
			}
			if tt.deploy != "" {
				files["pkg/deploy/deploy.go"] = tt.deploy
			}
			if tt.test != "" {
				files["pkg/deploy/deploy_test.go"] = tt.test
			}
			for rel, content := range files {
				abs := filepath.Join(dir, filepath.FromSlash(rel))
				if err := os.MkdirAll(filepath.Dir(abs), 0o750); err != nil {
					t.Fatalf("os.MkdirAll() error = %v", err)
				}
				if err := os.WriteFile(abs, []byte(content), 0o644); err != nil {
					t.Fatalf("os.WriteFile() error = %v", err)
				}
			}
			a, err := app.Discover(dir)
			if err != nil {
				t.Fatalf("app.Discover() error = %v", err)
			}
			want := tt.want
			if tt.deploy != "" {
				line := strconv.Itoa(sourceLine(t, tt.deploy, "resource.RetireSecretVersion("))
				want.Summary = strings.ReplaceAll(want.Summary, "<call>", line)
				for i, d := range want.Details {
					want.Details[i] = strings.ReplaceAll(d, "<call>", line)
				}
			}
			if diff := cmp.Diff(want, secretHolders{}.Run(context.Background(), &Env{App: a})); diff != "" {
				t.Errorf("Run() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

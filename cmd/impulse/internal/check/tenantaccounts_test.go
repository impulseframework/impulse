// TestTenantAccountsCandidates holds the skeleton candidates to the check, and the check
// to a refusal: the tenanted shapes grant every account method under the rule over the
// person's row, the solo shape has no tenant, and a grant that loses its condition, or
// carries one that reads nothing of the person, is named.
func TestTenantAccountsCandidates(t *testing.T) {
	t.Parallel()

	const (
		roles   = "pkg/auth/staff/roles.json"
		disable = "              \"resource\": \"DisableStaffTenantUser\",\n              \"condition\": \"heldElsewhere = false AND heldGlobally = false\"\n"
		rename  = "              \"resource\": \"RenameStaffTenantUser\",\n              \"condition\": \"heldElsewhere = false AND heldGlobally = false\"\n"
		rule    = ", so every tenant's holder of the role may change the account of a person another tenant or the whole application also holds; state the application's rule in the grant's condition over the person's row (heldElsewhere = false AND heldGlobally = false keeps an account to the tenant that alone holds the person)"
	)
	tests := []struct {
		name        string
		candidate   string
		edits       []candidateEdit
		wantStatus  Status
		wantSummary string
		wantDetails []string
	}{
		{
			name:        "the tenanted skeleton grants every account method under the rule",
			candidate:   "tenanted",
			wantStatus:  Pass,
			wantSummary: "10 grant(s) of a tenant's roles on the methods that change a person's account, each under a condition that reads the person's row",
			wantDetails: []string{roles + ": 10 grant(s) on the staff auth's account methods, each under a condition that reads the person's row"},
		},
		{
			name:        "two auths, the members without a password to set",
			candidate:   "outlets",
			wantStatus:  Pass,
			wantSummary: "18 grant(s) of a tenant's roles on the methods that change a person's account, each under a condition that reads the person's row",
			wantDetails: []string{
				"pkg/auth/members/roles.json: 8 grant(s) on the members auth's account methods, each under a condition that reads the person's row",
				roles + ": 10 grant(s) on the staff auth's account methods, each under a condition that reads the person's row",
			},
		},
		{
			name:        "two sites, the management generated by one",
			candidate:   "sites",
			wantStatus:  Pass,
			wantSummary: "10 grant(s) of a tenant's roles on the methods that change a person's account, each under a condition that reads the person's row",
			wantDetails: []string{roles + ": 10 grant(s) on the staff auth's account methods, each under a condition that reads the person's row"},
		},
		{
			name:        "an application with no tenant record is skipped",
			candidate:   "solo",
			wantStatus:  Skip,
			wantSummary: "no program generates the management of an auth's people beside a tenant record",
		},
		{
			name:        "a grant with no condition is named",
			candidate:   "tenanted",
			edits:       []candidateEdit{{file: roles, old: disable, new: "              \"resource\": \"DisableStaffTenantUser\"\n"}},
			wantStatus:  Fail,
			wantSummary: "1 grant(s) let a tenant change a person's account with no rule about the person",
			wantDetails: []string{roles + ": the tenant role TenantAdministrator is granted Execute on DisableStaffTenantUser with no condition" + rule},
		},
		{
			name:        "a condition that reads the request alone states no rule about the person",
			candidate:   "tenanted",
			edits:       []candidateEdit{{file: roles, old: rename, new: "              \"resource\": \"RenameStaffTenantUser\",\n              \"condition\": \"new.username != 'administrator'\"\n"}},
			wantStatus:  Fail,
			wantSummary: "1 grant(s) let a tenant change a person's account with no rule about the person",
			wantDetails: []string{roles + ": the tenant role TenantAdministrator is granted Execute on RenameStaffTenantUser under \"new.username != 'administrator'\", which reads nothing of the person's row" + rule},
		},
		{
			name:        "a rule of the application's own over the row is the application's to choose",
			candidate:   "tenanted",
			edits:       []candidateEdit{{file: roles, old: disable, new: "              \"resource\": \"DisableStaffTenantUser\",\n              \"condition\": \"heldGlobally = false\"\n"}},
			wantStatus:  Pass,
			wantSummary: "10 grant(s) of a tenant's roles on the methods that change a person's account, each under a condition that reads the person's row",
			wantDetails: []string{roles + ": 10 grant(s) on the staff auth's account methods, each under a condition that reads the person's row"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			a := renderCandidate(t, tt.candidate, tt.edits...)
			got := tenantAccounts{}.Run(context.Background(), &Env{App: a})
			want := Result{Name: tenantAccountsName, Status: tt.wantStatus, Summary: tt.wantSummary, Details: tt.wantDetails}
			if diff := cmp.Diff(want, got); diff != "" {
				t.Errorf("Run() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

// methodTypeRE finds the method a generated source file declares.
var methodTypeRE = regexp.MustCompile(`(?m)^type ([A-Z][A-Za-z0-9]*) struct`)

// TestTenantAccountMethodsAreTheGenerators holds the check's list of account methods to
// the generator's own word: every tenant method the generator writes with the sentence
// that leaves the person's rule to the role file is one the check holds, and the check
// holds no other. A method added to the generator with that sentence fails here until
// the check knows it.
func TestTenantAccountMethodsAreTheGenerators(t *testing.T) {
	t.Parallel()

	const tree = "../skeleton/_candidates/tenanted/pkg/identity/staffidentity"
	entries, err := os.ReadDir(tree)
	if err != nil {
		t.Fatal(err)
	}
	var stated []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasPrefix(e.Name(), "zz_gen_") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(tree, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		// The sentence as the generator writes it, whatever line it wraps on.
		text := strings.Join(strings.Fields(strings.ReplaceAll(string(data), "//", " ")), " ")
		if !strings.Contains(text, "is the role file's to say, in a condition on the method's grant that reads the facts of the row") {
			continue
		}
		m := methodTypeRE.FindStringSubmatch(string(data))
		if m == nil {
			t.Fatalf("%s states the rule and declares no method", e.Name())
		}
		stated = append(stated, m[1])
	}
	sort.Strings(stated)
	held := tenantAccountMethods("staff", "Tenant")
	sort.Strings(held)
	if len(stated) == 0 {
		t.Fatal("no generated method of the tenanted skeleton states the rule: the sentence the test looks for is no longer the generator's")
	}
	if !slices.Equal(stated, held) {
		t.Errorf("the generator leaves the person's rule to the role file on %q; the check holds %q", stated, held)
	}
}

func TestAccountGrantProblem(t *testing.T) {
	t.Parallel()

	tests := []struct {
		condition string
		want      string
	}{
		{condition: "heldElsewhere = false AND heldGlobally = false"},
		{condition: "heldElsewhere = false"},
		{condition: "new.role != 'TenantAdministrator' AND heldGlobally = false"},
		{condition: "", want: "with no condition"},
		{condition: "   ", want: "with no condition"},
		{condition: "new.role != 'TenantAdministrator'", want: `under "new.role != 'TenantAdministrator'", which reads nothing of the person's row`},
		{condition: "heldElsewhere = ", want: `under "heldElsewhere = ", which does not parse`},
	}
	for _, tt := range tests {
		if got := accountGrantProblem(tt.condition); got != tt.want {
			t.Errorf("accountGrantProblem(%q) = %q, want %q", tt.condition, got, tt.want)
		}
	}
}

// The server says the brand in two places: the mail an auth sends names the application
// (session.MailSettings.Application, which each auth package holds as its Application
// constant), and the maintenance page shows the name and the logo (maintenance.Serve,
// which a main hands the brands). The server cannot read the declaration where it sits:
// a browser application lies under the web workspace's own go.mod, the boundary that
// keeps Go's tools out of the installed packages, and go:embed refuses a file of another
// module. So the command writes what the server says into the module: a package,
// ServerPackage, holding each brand's name as a constant and its logo as an embedded PNG,
// and the name into the auth packages' constants.
const (
	// ServerPackage is the directory of the package the command writes for the server,
	// relative to the application root.
	ServerPackage = "pkg/brand"
	serverFile    = "brand.go"
)

// serverBrand is one brand as the server's package carries it.
type serverBrand struct {
	// Ident is the brand's identifier, the browser application's project name in PascalCase
	// (Console): the constant is <Ident>Name and the accessor <Ident>.
	Ident string
	// Var is the embedded logo's variable (consoleLogo) and Logo its file beside the
	// package's source (console.png).
	Var, Logo string
	// Name is the declared name as a Go string, and Declaration the declaration's path.
	Name, Declaration string
}

// serverSource is the package the command writes: one constant, one embedded logo and
// one accessor per brand.
var serverSource = template.Must(template.New(serverFile).Parse(`// Code generated by impulse brand. DO NOT EDIT.

// Package brand is the application's brands as the server says them: the name each
// browser application declares in its brand.json, which the mail an auth sends and the
// maintenance page say, and its logo, which the maintenance page shows. impulse brand
// writes this file and the logos beside it from the declarations, because the server
// cannot embed a declaration where it sits: a browser application lies under the web
// workspace's own go.mod, and go:embed reaches no file of another module. Change a
// declaration and run impulse brand again; a main hands the brands to maintenance.Serve
// by the mount path of each.
package brand

import (
	_ "embed"

	"github.com/impulseframework/impulse/resource/maintenance"
)
{{range .}}
// {{.Ident}}Name is the name {{.Declaration}} declares.
const {{.Ident}}Name = {{.Name}}

//go:embed {{.Logo}}
var {{.Var}} []byte

// {{.Ident}} is the brand {{.Declaration}} declares, as the maintenance page shows it:
// its name and its logo.
func {{.Ident}}() maintenance.Brand {
	return maintenance.Brand{Name: {{.Ident}}Name, Logo: {{.Var}}}
}
{{end}}`))

// server writes the server's package for the brands: the logos and the source.
func (w *writer) server(roots []*declared) error {
	brands := make([]serverBrand, 0, len(roots))
	taken := map[string]string{}
	for _, r := range roots {
		ident := identifier(r.Project)
		if ident == "" {
			return errors.Newf("the project %q of %s gives the server's package no name to call its brand by: a project is named in letters and digits, starting with a letter", r.Project, path.Join(r.Workspace, "angular.json"))
		}
		if other, ok := taken[ident]; ok {
			return errors.Newf("%s and %s are both the project %s, so the server's package (%s) cannot tell their brands apart: give the two projects different names in their angular.json", other, r.Dir, r.Project, ServerPackage)
		}
		taken[ident] = r.Dir
		b := serverBrand{Ident: ident, Var: strings.ToLower(ident[:1]) + ident[1:] + "Logo", Logo: serverLogoFile(r.Project), Name: strconv.Quote(r.declaration.Name), Declaration: r.DeclarationPath()}
		// The server's copy of the logo is written when the logo changed, and stands as
		// it is otherwise: it is what the next run tells a changed logo by.
		stands, err := w.logoStands(r)
		if err != nil {
			return err
		}
		err = w.cut(path.Join(ServerPackage, b.Logo), stands, func() ([]byte, error) {
			return r.logo.icon(serverLogoSize)
		})
		if err != nil {
			return err
		}
		brands = append(brands, b)
	}
	var source bytes.Buffer
	if err := serverSource.Execute(&source, brands); err != nil {
		return errors.Wrap(err, "template.Execute()")
	}
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return errors.Wrap(err, "format.Source()")
	}

	return w.put(path.Join(ServerPackage, serverFile), formatted)
}

// serverLogoFile is the name a project's logo carries in the server's package:
// console.png.
func serverLogoFile(project string) string {
	return strings.ToLower(identifier(project)) + ".png"
}

// identifier is a project's name as a Go identifier in PascalCase: admin-console is
// AdminConsole. A name with no letter to start from has none.
func identifier(project string) string {
	var b strings.Builder
	upper := true
	for _, r := range project {
		switch {
		case unicode.IsLetter(r) || (unicode.IsDigit(r) && b.Len() > 0):
			if upper {
				r = unicode.ToUpper(r)
			}
			b.WriteRune(r)
			upper = false
		default:
			upper = true
		}
	}

	return b.String()
}

// applicationConst matches an auth package's Application constant: the application's
// name as the mail the auth sends says it.
var applicationConst = regexp.MustCompile(`(?m)^(\s*Application\s*=\s*)` + doubleQuoted)

// mailNames writes each auth's name for the application, the Application constant of its
// package, from the brand of the browser application the auth's people sign in to: the
// one of the first browser outlet declaring the auth, in the generator programs' order.
// An auth bound to no branded browser application takes the application's only brand, and
// is left where there are several to choose between.
func (w *writer) mailNames(roots []*declared) error {
	bound := authApps(w.a, roots)
	for i := range w.a.AuthPackages {
		pkg := &w.a.AuthPackages[i]
		r, ok := bound[pkg.Path]
		if !ok && len(roots) == 1 {
			r, ok = roots[0], true
		}
		if !ok {
			w.left(pkg.Dir, fmt.Sprintf("no outlet with a branded browser application declares the %s auth, and the application has %d brands, so the name its mail says (the Application constant) was left as it is; set it to the brand it speaks for", pkg.Name, len(roots)))

			continue
		}
		if err := w.mailName(pkg, r); err != nil {
			return err
		}
	}

	return nil
}

// mailName writes the brand's name into the auth package's Application constant.
func (w *writer) mailName(pkg *app.AuthPackage, r *declared) error {
	entries, err := os.ReadDir(w.a.Abs(pkg.Dir))
	if err != nil {
		return errors.Wrap(err, "os.ReadDir()")
	}
	name := strconv.Quote(r.declaration.Name)
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		file := path.Join(pkg.Dir, entry.Name())
		data, err := os.ReadFile(w.a.Abs(file))
		if err != nil {
			return errors.Wrap(err, "os.ReadFile()")
		}
		if !applicationConst.Match(data) {
			continue
		}

		return w.put(file, []byte(replaceFirst(applicationConst, string(data), "${1}"+dollars(name))))
	}
	w.left(pkg.Dir, fmt.Sprintf("the %s auth declares no Application constant (Application = \"...\") for the name its mail says, so it was left as it is; hand session.MailSettings the brand's name there (%s.%sName)", pkg.Name, path.Base(ServerPackage), identifier(r.Project)))

	return nil
}

// authApps maps each auth package, by its import path, to the branded browser application
// its people sign in to: the one receiving the generated client of the first browser
// outlet that declares the auth.
func authApps(a *app.App, roots []*declared) map[string]*declared {
	byDir := make(map[string]*declared, len(roots))
	for _, r := range roots {
		byDir[r.Dir] = r
	}
	bound := map[string]*declared{}
	profile := a.Profile()
	for i := range profile.Sites {
		site := &profile.Sites[i]
		if site.Generator == nil {
			continue
		}
		outlets := append([]app.Outlet{site.Default}, site.Outlets...)
		for j := range outlets {
			o := &outlets[j]
			if o.Auth == nil || o.WebApp == "" {
				continue
			}
			if _, ok := bound[o.Auth.ImportPath]; ok {
				continue
			}
			for _, t := range site.Generator.TypescriptTargets() {
				if (j == 0 && t.Outlet != "") || (j > 0 && t.Outlet != o.Name) {
					continue
				}
				if r, ok := byDir[browserAppOf(a, t.Dir)]; ok {
					bound[o.Auth.ImportPath] = r

					break
				}
			}
		}
	}

	return bound
}

// browserAppOf is the directory of the browser application holding the directory: the
// project of its workspace whose root contains it, or empty.
func browserAppOf(a *app.App, dir string) string {
	w, ok := a.WebAppFor(dir)
	if !ok {
		return ""
	}
	projects, err := a.ReadAngular(w.Dir)
	if err != nil {
		return ""
	}
	rel := strings.TrimPrefix(strings.TrimPrefix(dir, w.Dir), "/")
	if project, ok := app.ProjectFor(projects, rel); ok {
		return path.Join(w.Dir, project.Root)
	}
	// A workspace whose one project sits at its root (the sites layout) names no
	// directory to find the project by.
	for i := range projects {
		if projects[i].Root == "." || projects[i].Root == "" {
			return w.Dir
		}
	}

	return ""
}

// unserved lists the brands no Go file hands to the maintenance page yet: the accessors
// of the server's package nothing outside it calls. A browser application an option added
// (impulse add outlet, impulse add site) is one until its main names it.
func unserved(a *app.App, roots []*declared) ([]*declared, error) {
	files, err := goSources(a)
	if err != nil {
		return nil, err
	}
	calls := make(map[string]bool, len(roots))
	for _, r := range roots {
		calls[accessorCall(r)] = false
	}
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			return nil, errors.Wrap(err, "os.ReadFile()")
		}
		for call := range calls {
			if bytes.Contains(data, []byte(call)) {
				calls[call] = true
			}
		}
	}
	var none []*declared
	for _, r := range roots {
		if !calls[accessorCall(r)] {
			none = append(none, r)
		}
	}

	return none, nil
}

// accessorCall is the call that hands a brand to the maintenance page, as a main writes
// it: brand.Console().
func accessorCall(r *declared) string {
	return path.Base(ServerPackage) + "." + identifier(r.Project) + "()"
}

// goSources lists the application's Go files outside the server's package, by absolute
// path: the files a main handing a brand to the maintenance page is looked for in.
func goSources(a *app.App) ([]string, error) {
	var files []string
	err := filepath.WalkDir(a.Root, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		name := d.Name()
		if d.IsDir() {
			if p != a.Root && (name == "node_modules" || name == "vendor" || name == "testdata" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") || p == a.Abs(ServerPackage)) {
				return filepath.SkipDir
			}

			return nil
		}
		if strings.HasSuffix(name, ".go") {
			files = append(files, p)
		}

		return nil
	})
	if err != nil {
		return nil, errors.Wrap(err, "filepath.WalkDir()")
	}

	return files, nil
}

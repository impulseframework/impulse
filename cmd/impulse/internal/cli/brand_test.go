// noWorkspacePackages stands in for the commands impulse brand runs in a browser
// workspace: the tests here run it where no packages are installed, so it runs none.
type noWorkspacePackages struct {
	t *testing.T
}

func (n noWorkspacePackages) Run(_ context.Context, dir string, _ []string, name string, _ ...string) ([]byte, error) {
	n.t.Fatalf("impulse brand ran %s in %s, where no packages are installed", name, dir)

	return nil, nil
}

// TestBrand runs the command over a freshly rendered application whose declaration was
// given a name of its own: it says what it did with each file of the declared brand and
// with the server's, and, where the workspace's packages are not installed, ends by saying
// the palette is missing and what to do. The logo is still the skeleton's, so the icons
// cut from it stand as the application has them, and the favicon, which the skeleton
// carries as an SVG the declaration does not name, becomes the PNG cut from the logo.
func TestBrand(t *testing.T) {
	t.Parallel()

	dir := filepath.Join(t.TempDir(), "beacon")
	if _, err := skeleton.Render(&skeleton.Options{Version: "v0.1.0", WebVersion: "0.1.0", Candidate: skeleton.Base, Dir: dir, ModulePath: "example.com/acme/beacon", Name: "beacon"}); err != nil {
		t.Fatalf("skeleton.Render() error = %v", err)
	}
	declaration := filepath.Join(dir, "web", "console", "brand.json")
	data, err := os.ReadFile(declaration)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(declaration, []byte(strings.Replace(string(data), `"Beacon"`, `"Beacon Light"`, 1)), 0o600); err != nil {
		t.Fatal(err)
	}

	cmd := newBrandWith(noWorkspacePackages{t: t})
	var out bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetErr(&out)
	cmd.SetArgs([]string{"--app", dir})
	cmd.SilenceUsage, cmd.SilenceErrors = true, true
	err = cmd.Execute()

	want := `web/console: Beacon Light (primary #005cbb, background #f6f7fb)
  removed    web/console/public/favicon.svg
  written    web/console/public/favicon.png
  unchanged  web/console/public/icons/icon-192.png
  unchanged  web/console/public/icons/icon-512.png
  unchanged  web/console/public/icons/icon-512-maskable.png
  written    web/console/public/manifest.webmanifest
  written    web/console/src/index.html
  written    web/console/src/app/app.config.ts
  left       web/console/src/_theme-colors.scss: the palette is generated by Angular Material's theme-color schematic, which comes with the packages of web, and they are not installed (no web/node_modules/.bin/ng); install them and run impulse brand again
The server (the mail the auths send and the maintenance page):
  unchanged  pkg/brand/console.png
  written    pkg/brand/brand.go
  written    pkg/auth/staff/staff.go
`
	if diff := cmp.Diff(want, out.String()); diff != "" {
		t.Errorf("the report mismatch (-want +got):\n%s", diff)
	}
	wantErr := "the brand of web/console is written but for the theme's palette, which Angular Material's generator writes once the workspace's packages are installed: install them and run impulse brand again"
	if err == nil || message(err) != wantErr {
		t.Errorf("Execute() error = %v, want %q", err, wantErr)
	}
}

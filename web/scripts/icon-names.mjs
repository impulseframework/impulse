// Writes the names of the Material Icons the library ships (the filled font, see
// copy-fonts.mjs) as a TypeScript union, projects/resource-angular/types/icon-names.ts, so
// an icon a menu or a page names is checked by the compiler: a misspelled name fails the
// build instead of drawing its letters. The names come from the font package's codepoints;
// run it after a font update (`bun run icons`), and the test beside the file fails until it
// is run.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

/** The icon names the font package lists, sorted and without repeats. */
export function shippedIconNames() {
  const codepoints = readFileSync(join(root, 'node_modules', 'material-icons', 'css', '_codepoints.scss'), 'utf8');
  const names = new Set();
  for (const match of codepoints.matchAll(/^\s*"([a-z0-9_]+)":\s*[0-9a-f]+,?\s*$/gm)) {
    names.add(match[1]);
  }
  return [...names].sort();
}

/** The file the script writes, from the names. */
export function iconNamesSource(names) {
  return [
    '// Code generated by scripts/icon-names.mjs from the material-icons package. DO NOT EDIT.',
    '',
    '/**',
    ' * The name of a Material Icon the library ships (the filled font). A menu entry, a page',
    ' * and every other place that names an icon in code takes this type, so a misspelled',
    ' * name fails the build.',
    ' */',
    'export type IconName =',
    ...names.map((name, i) => `  | '${name}'${i === names.length - 1 ? ';' : ''}`),
    '',
  ].join('\n');
}

if (import.meta.main ?? process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(root, 'projects', 'resource-angular', 'types', 'icon-names.ts');
  const names = shippedIconNames();
  writeFileSync(out, iconNamesSource(names));
  console.log(`wrote ${names.length} icon names to ${out}`);
}
